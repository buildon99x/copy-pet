//! macOS rich-format clipboard read/write via `NSPasteboard` (ADR-0014): the
//! macOS half of Win+V parity. On copy the portable watcher reads the original
//! HTML/RTF alongside the plain text; on paste `set_clipboard` re-emits them
//! (unless the user chose "paste as text", which writes plain text only).
//!
//! All `unsafe` here is Objective-C messaging, wrapped in an autorelease pool.
//! Only pasteboard data is touched — never a Text Input Source API — so this is
//! safe to call from the watcher thread (cf. LNR-0005, which is TIS-specific).

#![allow(unexpected_cfgs)] // objc 0.2's msg_send!/class! macros

use objc::runtime::BOOL;
use objc::{class, msg_send, sel, sel_impl};
use std::os::raw::c_char;

use crate::clipboard::{b64_decode, b64_encode, RichFormats};

use super::mac_util::{nsstring, Id};

// NSPasteboard uniform-type identifiers.
const UTF8_TEXT: &str = "public.utf8-plain-text";
const HTML: &str = "public.html";
const RTF: &str = "public.rtf";

unsafe fn nsstring_to_string(ns: Id) -> Option<String> {
    if ns.is_null() {
        return None;
    }
    let utf8: *const c_char = msg_send![ns, UTF8String];
    if utf8.is_null() {
        return None;
    }
    Some(std::ffi::CStr::from_ptr(utf8).to_string_lossy().into_owned())
}

unsafe fn nsdata_to_vec(data: Id) -> Option<Vec<u8>> {
    if data.is_null() {
        return None;
    }
    let len: usize = msg_send![data, length];
    let ptr: *const u8 = msg_send![data, bytes];
    if len == 0 || ptr.is_null() {
        return None;
    }
    Some(std::slice::from_raw_parts(ptr, len).to_vec())
}

/// Observe the pasteboard generation without reading any payload.
pub fn generation() -> isize {
    unsafe {
        let pool: Id = msg_send![class!(NSAutoreleasePool), new];
        let pb: Id = msg_send![class!(NSPasteboard), generalPasteboard];
        let count: isize = msg_send![pb, changeCount];
        let _: () = msg_send![pool, drain];
        count
    }
}

/// Use one pasteboard item for both its markers and payload, then verify that
/// the pasteboard did not change while a lazy provider rendered the data.
pub fn observe<P>(expected: isize, permit: impl FnOnce(Option<&str>) -> Option<P>)
    -> Option<(String, Option<String>, Option<RichFormats>, P)> {
    unsafe {
        let pool: Id = msg_send![class!(NSAutoreleasePool), new];
        let pb: Id = msg_send![class!(NSPasteboard), generalPasteboard];
        let result = observe_board(pb, expected, permit);
        let _: () = msg_send![pool, drain];
        result
    }
}

// Caller owns an autorelease pool and the pasteboard must be valid.
unsafe fn observe_board<P>(pb: Id, expected: isize, permit: impl FnOnce(Option<&str>) -> Option<P>)
    -> Option<(String, Option<String>, Option<RichFormats>, P)> {
    let types: Id = msg_send![pb, types];
    for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                   "org.nspasteboard.AutoGeneratedType"] {
        let present: BOOL = msg_send![types, containsObject: nsstring(marker)];
        if present == objc::runtime::YES { return None; }
    }
    let items: Id = msg_send![pb, pasteboardItems];
    let item: Id = msg_send![items, firstObject];
    if item.is_null() { return None; }
    let count: isize = msg_send![pb, changeCount];
    if count != expected { return None; }
    let workspace: Id = msg_send![class!(NSWorkspace), sharedWorkspace];
    let front: Id = msg_send![workspace, frontmostApplication];
    let name: Id = msg_send![front, localizedName];
    let source = nsstring_to_string(name);
    let permit = permit(source.as_deref())?;
    let plain: Id = msg_send![item, stringForType: nsstring(UTF8_TEXT)];
    let text = nsstring_to_string(plain)?;
    let html: Id = msg_send![item, stringForType: nsstring(HTML)];
    let rtf: Id = msg_send![item, dataForType: nsstring(RTF)];
    let formats = RichFormats { html: nsstring_to_string(html),
        rtf_b64: nsdata_to_vec(rtf).map(|bytes| b64_encode(&bytes)) };
    let after: isize = msg_send![pb, changeCount];
    (expected == after).then(|| (text, source, (!formats.is_empty()).then_some(formats), permit))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn local_write_receipt_identifies_its_pasteboard_generation() {
        unsafe {
            let pool: Id = msg_send![class!(NSAutoreleasePool), new];
            let board: Id = msg_send![class!(NSPasteboard), pasteboardWithUniqueName];
            let rich = RichFormats { html: Some("<b>Y</b>".into()), rtf_b64: None };
            let (own, complete) = write_board(board, "Y", Some(&rich)).expect("own rich write");
            assert!(complete);
            assert_eq!(observe_board(board, own, |_| Some(())).unwrap().0, "Y");
            let (external, _) = write_board(board, "Y", None).expect("second declaration");
            assert_ne!(own, external);
            assert!(observe_board(board, own, |_| Some(())).is_none());
            let _: () = msg_send![board, releaseGlobally];
            let _: () = msg_send![pool, drain];
        }
    }

    #[test]
    fn privacy_marked_pasteboard_item_is_ignored() {
        // A unique pasteboard does not touch the user's general pasteboard.
        unsafe {
            let pool: Id = msg_send![class!(NSAutoreleasePool), new];
            let board: Id = msg_send![class!(NSPasteboard), pasteboardWithUniqueName];
            let _: isize = msg_send![board, clearContents];
            let ok: BOOL = msg_send![board, setString: nsstring("synthetic") forType: nsstring(UTF8_TEXT)];
            assert_eq!(ok, objc::runtime::YES);
            let count: isize = msg_send![board, changeCount];
            assert_eq!(observe_board(board, count, |_| Some(())).unwrap().0, "synthetic");
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType"] {
                let _: isize = msg_send![board, clearContents];
                let _: BOOL = msg_send![board, setString: nsstring("synthetic") forType: nsstring(UTF8_TEXT)];
                let _: BOOL = msg_send![board, setString: nsstring("") forType: nsstring(marker)];
                let generation: isize = msg_send![board, changeCount];
                assert!(observe_board(board, generation, |_| Some(())).is_none());
            }
            let _: () = msg_send![board, releaseGlobally];
            let _: () = msg_send![pool, drain];
        }
    }
}

/// Replaces the pasteboard with `text` plus the given rich `formats` (when
/// present). `formats: None` writes plain text only.
pub fn write(text: &str, formats: Option<&RichFormats>) -> Option<(isize,bool)> {
    unsafe {
        let pool: Id = msg_send![class!(NSAutoreleasePool), new];
        let pb: Id = msg_send![class!(NSPasteboard), generalPasteboard];
        let result = write_board(pb, text, formats);
        let _: () = msg_send![pool, drain];
        result
    }
}

// setString/setData add types to our declared pasteboard contents. A new
// declaration by another process changes the generation returned by clearContents.
unsafe fn write_board(pb: Id, text: &str, formats: Option<&RichFormats>) -> Option<(isize,bool)> {
    let declared: isize = msg_send![pb, clearContents];
    let ok: BOOL = msg_send![pb, setString: nsstring(text) forType: nsstring(UTF8_TEXT)];
    if ok != objc::runtime::YES { return None; }
    let mut complete = true;
    if let Some(f) = formats {
        if let Some(html) = &f.html {
            let ok: BOOL = msg_send![pb, setString: nsstring(html) forType: nsstring(HTML)];
            complete &= ok == objc::runtime::YES;
        }
        if let Some(rtf_b64) = &f.rtf_b64 {
            if let Some(bytes) = b64_decode(rtf_b64) {
                let data: Id =
                    msg_send![class!(NSData), dataWithBytes: bytes.as_ptr() length: bytes.len()];
                let ok: BOOL = msg_send![pb, setData: data forType: nsstring(RTF)];
                complete &= ok == objc::runtime::YES;
            } else { complete = false; }
        }
    }
    let current: isize = msg_send![pb, changeCount];
    (current == declared).then_some((current,complete))
}
